    private void buttonEvalActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_buttonEvalActionPerformed
        // TODO add your handling code here:
        if(symbolsDeque.isEmpty()) {
            if (ans != null) {
                symbolsDeque.add(ans);
            } else if (!currentSequence.isEmpty()){
                try {
                    double val = Double.parseDouble(currentSequence);
                    currentSequence = "";
                    symbolsDeque.add(new CalcNumber(val));
                    outputValue.setText(getDequeAsString());
                } catch (Exception e) {
                    System.err.println("Cannot parse the entered number. Please correct it before trying to continue.");
                }
            } else {
                System.err.println("Calculator output is empty!");
                outputValue.setText("");
                return;
            }
        }
        
        try {
            while(!symbolsDeque.isEmpty()) {
                if(symbolsDeque.peekFirst() instanceof CalcNumber) {
                    numberAwaitCalc.addLast((CalcNumber)symbolsDeque.pollFirst());
                    continue;
                }

                if(symbolsDeque.peekFirst() instanceof AbstractOperator) {
                    CalcNumber rightVal = numberAwaitCalc.pollLast();
                    CalcNumber leftVal;
                    AbstractOperator operator = (AbstractOperator)symbolsDeque.pollFirst();

                    if(rightVal == null) throw new ArithmeticException("The next operator cannot be evaluated due to lack of number!");

                    try {
                        numberAwaitCalc.addLast(operator.evaluate(rightVal));
                    } catch (UnsupportedOperationException use) {
                        leftVal = numberAwaitCalc.pollLast();

                        if(leftVal == null) throw new ArithmeticException("The next operator cannot be evaluated due to lack of number!");
                        numberAwaitCalc.addLast(operator.evaluate(leftVal, rightVal));
                    }
                }
            }
            
            CalcNumber prevAns = ans != null? new CalcNumber(ans.getValue()) : null;
            ans = numberAwaitCalc.pollLast();
            if (!numberAwaitCalc.isEmpty() && prevAns != null) {
                ans = prevAns;
                throw new ArithmeticException("Unevaluated number in expression!");
            }
            
            outputValue.setText(ans.getValue() + "");
        } catch (Exception e) {
            System.err.println("A problem has occured while trying to evaluate expression. Detail: ");
            e.printStackTrace();
            outputValue.setText("Error");
            symbolsDeque.clear();
            numberAwaitCalc.clear();
        } finally {
            isEvaluated = true;
        }
    }//GEN-LAST:event_buttonEvalActionPerformed

