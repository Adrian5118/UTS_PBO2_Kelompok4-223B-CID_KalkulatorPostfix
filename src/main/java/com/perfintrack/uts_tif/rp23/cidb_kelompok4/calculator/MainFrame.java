    private void moveAnsToOutputAnswer() {
        if(isEvaluated) {
            if(ans == null) {
                outputValue.setText("");
                isEvaluated = false;
                return;
            }
            
            symbolsDeque.add(ans);
            outputValue.setText(getDequeAsString());
            outputAnswer.setText("Ans: " + ans.getValue());
            
            isEvaluated = false;
        }
    }
    
    private void removeLastCharFromSequence() {
        if(currentSequence != null && !currentSequence.trim().isEmpty()) {
            currentSequence = currentSequence.substring(0, currentSequence.length() - 1);
        }
    }
    
    private void addCharToSequence(char symbol) {
        moveAnsToOutputAnswer();
        
        currentSequence += symbol;
        outputValue.setText(outputValue.getText() + symbol);
    }
    
    private void addOperatorToDeque(AbstractOperator operator) {
        moveAnsToOutputAnswer();
        
        if(!currentSequence.isEmpty()) {
            try {
                double val = Double.parseDouble(currentSequence);
                currentSequence = "";
                symbolsDeque.add(new CalcNumber(val));
                symbolsDeque.add(operator);
                outputValue.setText(getDequeAsString());
            } catch (Exception e) {
                System.err.println("Cannot parse the entered number. Please correct it before trying to continue.");
            }
        } else {
            symbolsDeque.add(operator);
            outputValue.setText(getDequeAsString());
        }
    }
    
    private String getDequeAsString() {
        String returnString = "";
        
        for(ICalcObject calcObject: symbolsDeque) {
            if (calcObject instanceof AbstractOperator) {
                returnString += ((AbstractOperator) calcObject).getChar() + " ";
            }
            if (calcObject instanceof CalcNumber) {
                returnString += ((CalcNumber) calcObject).getValue() + " ";
            }
        }
        
        return returnString;
    }

