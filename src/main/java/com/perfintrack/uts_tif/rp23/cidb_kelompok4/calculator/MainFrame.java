    private void buttonDelActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_buttonDelActionPerformed
        // TODO add your handling code here:
        // Check if current symbols sequence is empty
        moveAnsToOutputAnswer();
        if(currentSequence.isEmpty()) {
            if (symbolsDeque.isEmpty()) {
                System.out.println("Nothing else to delete");
                return;
            }
            if (symbolsDeque.peekLast() instanceof CalcNumber) {
                currentSequence = ((CalcNumber)symbolsDeque.getLast()).getValue() + "";
                removeLastCharFromSequence();
                symbolsDeque.removeLast();
                outputValue.setText(getDequeAsString() + currentSequence);
                return;
            }
            if (symbolsDeque.peekLast() instanceof AbstractOperator) {
                symbolsDeque.removeLast();
                outputValue.setText(getDequeAsString());
            }
        } else {
            removeLastCharFromSequence();
            outputValue.setText(getDequeAsString() + currentSequence);
        }
    }//GEN-LAST:event_buttonDelActionPerformed

